const express =
  require("express");

const {
  register,
  login,
} = require("./auth.controller");

const router =
  express.Router();


// =========================================================
// REGISTER
// =========================================================

router.post(
  "/register",
  register
);


// =========================================================
// LOGIN
// =========================================================

router.post(
  "/login",
  login
);


// =========================================================
// EXPORT
// =========================================================

module.exports =
  router;